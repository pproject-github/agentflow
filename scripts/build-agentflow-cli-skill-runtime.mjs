#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const packageManifest = JSON.parse(fs.readFileSync(path.join(repoRoot, "package.json"), "utf-8"));
const runtimeDir = path.join(repoRoot, "skills", "agentflow-cli", "runtime");
const runtimeEntry = path.join(runtimeDir, "bin", "lib", "skill-runtime.mjs");
const builtinNodesDir = path.join(runtimeDir, "builtin", "nodes");

fs.mkdirSync(path.dirname(runtimeEntry), { recursive: true });
fs.mkdirSync(builtinNodesDir, { recursive: true });

await build({
  entryPoints: [path.join(repoRoot, "bin", "lib", "skill-runtime.mjs")],
  outfile: runtimeEntry,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  legalComments: "none",
  banner: {
    js: `// Generated by scripts/build-agentflow-cli-skill-runtime.mjs for AgentFlow ${packageManifest.version}.`,
  },
});

fs.cpSync(path.join(repoRoot, "builtin", "nodes"), builtinNodesDir, { recursive: true });

const runtimeManifest = {
  name: "@fieldwangai/agentflow-skill-runtime",
  version: packageManifest.version,
  type: "module",
  agentflowSkillRuntime: 1,
};
fs.writeFileSync(
  path.join(runtimeDir, "package.json"),
  `${JSON.stringify(runtimeManifest, null, 2)}\n`,
  "utf-8",
);
